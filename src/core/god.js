/**
 * 订单冲击 —— 价格位移层
 * ===============================================================
 * 位移只在**一个地方**生效：`market.candleAt`。
 * （markPrice / 权益 / 强平价 / 资金费 / K 线图 / HUD 涨跌幅全部经由它 ⇒ 下游一行都不用改。）
 *
 *   订单冲击 `s.flow[sym]` —— **逐根**衰减（Bouchaud 幂律：永久分量 ＋ 慢幂律 ＋ 快回，§73.3）。
 *   **开仓、平仓、
 *   强平**都写一笔；平仓 / 强平取持仓的反面方向，但**只回吐 `SHOCK.closeGive`**（2026-10-02 拍板）
 *   —— 往返不再等量抵消：一次完整往返净留开仓冲击的 **55.25%**，玩家每一笔成交都在图上留下台阶。
 *   C1（2026-09-29）起是**逐笔列表**（`[{v, at}, …]`），残存值按笔叠加。
 *   ⚠️ 2026-10-02 起**不再有笔数上限**（原来的 `listMax = 8` ＋ `collapse` 已删，见 `SHOCK`）。
 *
 *   持仓抛压折价 `s.overhang[sym]` —— **台阶表** `{ at:[], v:[], scar:[] }`，不衰减的折价，
 *   由「你的现货实物多头占了多少可交易浮筹」算出（`FLOAT`，2026-10-01）。它与 `s.flow`
 *   相加成同一个系数 —— 见 `overhangAt`。
 *
 * ⚠️ **位移层的硬纪律（2026-10-02）**：`s.flow` / `s.overhang` / `s.mkt[sym].npcDrift`
 *    三者写入时，`at` 只许等于**写入那一刻的 `s.i`**、只许**追加**，绝不回头改已画出的根。
 *    违反它 = 玩家看到「已经画出来的 K 线过几个小时又恢复了」＋「整屏重标定的断层」
 *    （三个实例：`refreshOverhang` 重盖 `at` / `syncNpcDrift` 每小时重盖 `at` / `collapse` 盖在 `now`）。
 *    见 NEXT-STEPS §九。
 *
 * ⚠️ 上帝模式（`s.god`）**没有任何价格能力**（2026-09-29 瘦身）：它只剩「跳日期 ＋ 填资金 ＋ 归零不退出」，
 *    与普通模式的差别**仅此三条**。原来那两套价格能力已整体删除 ——
 *      ① `s.god.scale` 手动设价（全局永久乘数）
 *      ② `s.god.mult` 冲击倍率（把 `SHOCK.share` 乘上 ×10 / ×100）
 *    玩家看到的「平仓后价格弹得比原价还高」「K 线缓升后平仓暴涨」全都出自这两条：
 *    位移唯一真正的来源就是**订单冲击**，而它按拟线性的平方根定律封顶（单笔收益 ≤ 10.5%）。
 *
 * ⚠️ 为什么位移必须是**逐根**系数、不能写成「当前时刻的全局常数」：
 *    一笔单只影响它**之后**的行情（`j < at` ⇒ 系数 1），这才对得上「价格从那一根开始下台阶、
 *    再按幂律慢慢爬回」。写成全局常数会让历史 K 线跟着一起缩放（图像像被重新标定过），
 *    而且**收益率不变 ⇒ σ_30日不变**，与「冲击真的发生了」直接矛盾。
 *
 * ⚠️ 逐根系数在**图上怎么用**是另一条纪律（2026-10-02）：`market.candleAt` 用「**上一根**的系数
 *    定开盘、本根的系数定收盘、两者的极值包住最高 / 最低」⇒ 成交那一刻是一段**连续价格路径**，
 *    不是整根平移。原来 o/h/l/c 同乘一个 f，`at−1 → at` 之间会凭空裂开一个跳空缺口，
 *    图上就是「一根悬浮的孤立 K 线」，而且整根平移 ⇒ 实体形状不变 ⇒ 看不出「我把订单薄吃了」。
 *
 * ⚠️ 逐根系数的代价必须记住：相邻收益率会变 ⇒ σ_30日会变 ⇒ 滑点与资金费率连带变。
 *    所以 `engine.invalidateSigma()` 必须在**每次写 `s.flow` 之后**调用，
 *    否则会算出「价格在动、波动率不动」的不自洽滑点。
 */

