function npcDriftAt(s, sym, j) {
  return stepValueAt(s.mkt && s.mkt[sym] && s.mkt[sym].npcDrift, j);
}

/**
 * 指数核的**静态衰减表**（NEXT-STEPS §8.7 · 方案 B′ · 2026-10-02）—— `DECAY[e] = 0.5^(e / shockHalf)`。
 *
 * ⚠️ **为什么要有它**：`npcShockAt` 要对**每一条**历史冲击求和，而 `factorFor` 被 `view.js` 逐根调用
 *    （可见窗口最多 240 根 × 每个已加载币）⇒ 12 年峰值下一帧的 `Math.pow` 次数可达 3×10⁶，
 *    实测 **30.0 ms / 帧**（合成 10537 条 × 60 根 × 5 币），是真正的帧预算杀手。
 *    换成一次表查之后实测 **1.8 ms / 帧**（约 16×），**逐位无损**（误差只来自 `Math.pow` 与建表同源）。
 * ⚠️ 表长取 **200 个半衰期**（`2⁻²⁰⁰ < 1e-60`）：再往后的贡献小于浮点噪声，一律按 0 计。
 *    4800 × 8B ≈ 38 KB，**全局一张**、不随币数增长、**不进存档**。
 */
const DECAY_MAX = 200 * NPC.shockHalf;
const DECAY = new Float64Array(DECAY_MAX);
for (let e = 0; e < DECAY_MAX; e++) DECAY[e] = Math.pow(0.5, e / NPC.shockHalf);

/**
 * 第 j 根上**NPC 级联成交**留下的瞬时冲击（v28 · 2026-10-02）。
 *
 * 形状与 `npcDrift` 一样是**只许追加的平行数组** `{ at: [], v: [] }`（`at` 恒等于写入那一刻的
 * `s.i` ⇒ 历史永不回头改写），但**取值方式不同**：不是「最后一个 `at ≤ j` 的台阶」，而是
 * **对每一笔按指数衰减求和** —— `Σ v_k × 0.5^((j − at_k) / NPC.shockHalf)`。
 *
 * ⚠️ 为什么不能写进 `s.flow`：那是**玩家**的永久痕迹通道（`perm ≥ 0.4` ＋ 慢幂律 `β = 0.3`），
 *    NPC 每小时都在注入 ⇒ `Σ t^-0.3` 无界累积，实测把显示价顶死在 `riseMax` 夹子上 97.67% 的时间。
 *    指数衰减的累积有上界（≈ 每小时注入量 × 34），级联因此「砸一波、数天内修复」。
 * @param {number} j 小时序号（可以是历史根）
 */
function npcShockAt(s, sym, j) {
  const tab = s.mkt && s.mkt[sym] && s.mkt[sym].npcShock;
  if (!tab || !tab.at.length) return 0;
  let sum = 0;
  for (let k = 0; k < tab.at.length; k++) {
    const e = j - tab.at[k];
    /* ⚠️ `break` 而不是 `continue`（方案 B′）：`at` **严格升序** —— 写入点 `pushNpcShock` 只往
       `at = 那一刻的 s.i` 追加、同小时还会合并；而 `rewindTo` 是**整条 `s.mkt` 归零重来**
       （`engine.js` 那句 `s.mkt = {}`）⇒ 永远不会出现「后来的 `at` 更小」。
       这一条顺带把**回顾页拖回 2013** 那种「j 远早于表尾」的读法从 O(n) 砍成 O(命中条数)。 */
    if (e < 0) break;                          // `at` 之后才生效（升序 ⇒ 之后全部无效）
    if (e < DECAY_MAX) sum += tab.v[k] * DECAY[e];
  }
  return sum;
}

/**
 * **玩家侧**的价格位移系数（不含 NPC 那层）—— 只有订单冲击＋持仓折价。
 * ⚠️ 热度的价格输入用它（见 `HEAT` 的口径注释）：玩家的成交要算进去（否则烧不起跟风），
 *    NPC 自己的连续偏移要剔除（否则会自激）。
 */
export function playerFactor(s, sym, j) {
  return shockFactorOf(residualAt(s, sym, j) + overhangAt(s, sym, j));
}

/**
 * 第 j 根的**价格位移系数** —— `market.candleAt` 唯一要乘的那个数。
 * 没有任何位移时恒等于 1（⇒ 与数据包逐位相同）。
 *
 * 三个来源相加：**订单冲击**（逐笔、幂律衰减）＋ **持仓抛压折价**（台阶表、不衰减）
 *             ＋ **NPC 散户净持仓偏移**（有界、台阶表）＋ **NPC 级联瞬时冲击**（有界、指数衰减）。
 *
 * ⚠️ 最后一项**只进这里、不进 `playerFactor`** —— 与 `npcDrift` 同一条纪律：
 *    热度的价格输入若含 NPC 自己的位移，就会自激（§73.5）。
 *
 * **两侧同时夹**（B1，2026-09-29；2026-10-02 收紧为 `SHOCK.fallMax` / `SHOCK.riseMax`）。
 */
export function factorFor(s, sym, j) {
  return shockFactorOf(residualAt(s, sym, j) + overhangAt(s, sym, j) + npcDriftAt(s, sym, j) + npcShockAt(s, sym, j));
}

/** 把一份「位移总量」夹进 `fallMax ~ riseMax` 并转成乘数（两个入口共用，保证同形） */
function shockFactorOf(r) {
  if (!r) return 1;
  const f = 1 + Math.min(SHOCK.riseMax, Math.max(SHOCK.fallMax, r));
  return f > 1e-9 ? f : 1e-9;
}

