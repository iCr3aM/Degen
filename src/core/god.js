/** 某一时刻**全市场可得**的最高杠杆（升序取「最后一个 `from <= t`」；早于首档一律 1）
 *  ⚠️ 不导出（2026-10-04 审计 R5）：仅 `npcLevOf` 用，放出去只会多一套「杠杆上限」口径。 */
function levCapAt(t) {
  let cap = 1;
  for (const s of LEV_CAP_STEPS) { if (s.from <= t) cap = s.cap; else break; }
  return cap;
}

/**
 * 某一时刻、某一档的**生效杠杆** = `min(基准档位, 年代封顶)`。
 * ⚠️ `NPC.ladder[k].lev` / `NPC.mm.lev` 是**基准值**，真正进强平线 / 止损带公式的必须是本函数的返回值。
 */
export const npcLevOf = (t, base) => Math.min(base, levCapAt(t));

/**
 * 衰减因子：`e` = 距写入时刻经过的**游戏小时数**（§73.3 · 2026-10-02 重写）。
 *
 * 「**永久分量 ＋ 慢幂律 ＋ 快回**」三段叠加 —— 取代原来的「2 小时内滑到 85% 地板、此后永久不变」：
 *   收敛到 `perm`（文献里 ≈ 首日冲击的一半），永远不会归零，所以玩家留下的台阶**永久**在图上。
 * ⚠️ 过冲（先砸过头再修复）**不写在这里** —— 它由 NPC 恐慌盘的真实订单流产生（§73.4）。
 * @param {number} e 经过的游戏小时数
 * @param {{perm:number, betaFast:number}} [p] 该笔成交的形态参数（缺省用 `SHOCK` 的中性值）
 * ⚠️ 不导出（2026-10-04 审计 R5）：仅 `residualAt` 用，衰减形态不许外部另算一份。
 */
function decay(e, p) {
  if (!(e > 1)) return 1;          // e ≤ 1（含 0 与负数）一律视为「刚开始」，不衰减
  const perm = p?.perm ?? SHOCK.perm;
  const betaFast = p?.betaFast ?? SHOCK.betaFast;
  const slow = Math.pow(e, -SHOCK.betaSlow);
  const fast = Math.pow(e, -betaFast);
  return perm + (1 - perm) * ((1 - SHOCK.fastWeight) * slow + SHOCK.fastWeight * fast);
}

/**
 * 某个币在**第 j 根**上残存的订单冲击量（0 = 没有冲击、j 早于写入时刻）。
 *
 * C1（2026-09-29）：池子由「单池」改成**逐笔的 propagator 列表** ——
 *   `residual(j) = Σ v_k × decay(j − at_k)`，这才是 Bouchaud 的叠加式。
 *   单池模型的毛病：分 10 笔买进去，第 2 笔会把第 1 笔的衰减进度**吃掉**
 *   （一笔 1 小时前的单和一笔 100 小时前的单被合并成「刚刚发生的一笔」）。
 * ⚠️ 不导出（2026-10-04 审计 R5）：仅本模块 `factorFor` 用，外部一律走 `factorFor`。
 */
function residualAt(s, sym, j) {
  const list = s.flow && s.flow[sym];
  if (!list || !list.length) return 0;
  let v = 0;
  for (const p of list) {
    if (!p.v || j < p.at) continue;
    v += p.v * decay(j - p.at, p);      // 每笔自带 `perm` / `betaFast`（§73.6 三模式形态）
  }
  return v;
}

/**
 * 把一笔成交的永久冲击**追加**进池子。
 *
 * 唯一允许的缩短方式：**同一根小时 ＋ 同一形态参数**的若干笔直接相加 —— `at` / `perm` /
 * `betaFast` 三项全同 ⇒ `decay(j − at)` 完全相同 ⇒ 合并**逐位等价**，不损失任何精度。
 *
 * ⚠️ **绝不做「改 `at`」的归并**（2026-10-02，NEXT-STEPS §九 根因 ③）：任何把 `at` 往后挪的
 *    压缩都会让所有 `j < 新 at` 的根**丢掉这几笔的残值** —— 图上就是「已经画出来的 K 线
 *    过几个小时又恢复了」。列表长度因此不再设硬上界（条数 = 有成交的小时数）。
 * @param {{perm:number, betaFast:number}} [p] 这一笔的形态参数（§73.6）；缺省用 `SHOCK` 的中性值
 * @returns {boolean} 是否真的写进去了（Δ 为 0 时不写，避免无意义地刷存档）
 */
export function addFlow(s, sym, delta, p) {
  if (!Number.isFinite(delta) || delta === 0) return false;
  if (!s.flow) s.flow = {};
  const list = s.flow[sym] || (s.flow[sym] = []);
  const perm = p?.perm ?? SHOCK.perm;
  const betaFast = p?.betaFast ?? SHOCK.betaFast;
  const tail = list[list.length - 1];
  if (tail && tail.at === s.i && tail.perm === perm && tail.betaFast === betaFast) tail.v += delta;
  else list.push({ v: delta, at: s.i, perm, betaFast });
  return true;
}

/**
 * 「逐根台阶表」取第 j 根的值 == **最后一个 `at <= j`** 的那一项（没有 ⇒ 0）。
 *
 * 表形状：`{ at: number[], v: number[], scar?: number[] }` —— **三条平行数组**，按 `at` 升序。
 * 用平行数组而不是 `[{ at, v, scar }]`：持仓折价的**按日重算**会让表长到数千项
 * （一趟全周期约 4400 天），对象形式在存档里约 45 字符/项，平行数组只约 18 字符/项。
 *
 * ⚠️ **位移层的硬纪律（2026-10-02 起）**：凡写 `s.flow` / `s.overhang` / `s.mkt[sym].npcDrift`，
 *    `at` **只许等于写入那一刻的 `s.i`、只许追加** —— 任何一次「回头改 `at`」都会让
 *    **已经画出来的根**在玩家眼皮底下变形（NEXT-STEPS §九 的三个根因全部出自这一条）。
 * @param {{at:number[], v:number[], scar?:number[]}} tab
 * @param {number} j 小时序号（可以是历史根）
 * @param {'v'|'scar'} key 取哪一条平行数组
 */
function stepValueAt(tab, j, key = 'v') {
  if (!tab) return 0;
  const at = tab.at;
  const arr = tab[key];
  if (!arr || !at.length) return 0;
  let lo = 0, hi = at.length - 1, hit = -1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (at[mid] <= j) { hit = mid; lo = mid + 1; } else hi = mid - 1;
  }
  return hit < 0 ? 0 : arr[hit];
}

/**
 * 第 j 根上**持仓集中度**造成的抛压折价（2026-10-01 用户拍板）—— 恒为负值（0 = 没持有）。
 *
 * 与 `s.flow` 是**两套东西**，别混：
 *   `flow`     = 你**下单**那一刻砸出的台阶，按幂律衰减、收敛到永久分量 `perm`
 *   这里       = 你**持仓**本身带来的折价 —— 市场忌惮你随时砸盘，于是先给价格打个折。
 *                **不衰减**（只要你还没卖，这份忌惮就一直在），卖出后归零。
 *
 * ⚠️ 存成**逐根台阶**（而不是「按当前持仓实时算」）是**必须**的：`factorFor` 会被每一根
 *    （含历史）调到，若按当前持仓实时算，玩家一买入**整条历史 K 线都会被重新标定**
 *    （与 `s.flow` 逐根约束同一个理由）。`at` 之前的 K 线一律不受影响。
 *
 * ⚠️ 2026-10-02 起是**台阶表** `{ at:[], v:[], scar:[] }`（NEXT-STEPS §九 根因 ①）——
 *    原来只有**单条** `{ v, at }`：每次重算都用新 `at` 覆盖旧 `at`，于是 `[旧 at, 新 at)`
 *    这一整段已画出的历史**全部丢掉折价**、逐位打回。实测一笔 $4M 的单反复往返后，
 *    被回头改写的根从 1 涨到 **40/40**，主犯就是这里。
 */
function overhangAt(s, sym, j) {
  return stepValueAt(s.overhang && s.overhang[sym], j);
}

/**
 * 第 j 根上**NPC 散户净持仓**对价格的偏移（2026-10-02 · §73.5 审计修）—— 恒 ≤ 0 或 ≥ 0（0 = 无仓位）。
 *
 * 与 `overhangAt` **同一套「逐根台阶」范式**（`j >= at` 才生效）：散户的仓位每小时都在动，
 * 若按「当前持仓实时算」，玩家一升级就会把**整条历史 K 线重新标定**（与 `s.flow` 同一条红线）。
 *
 * ⚠️ 2026-10-02 起也是**台阶表**（NEXT-STEPS §九 根因 ②）—— 原来只有单条 `{ v, at }`，
 *    而 `syncNpcDrift` **每小时无条件重盖 `at = s.i`** ⇒ 上一根 K 线每小时自己变一次。
 *    现在由写入侧按门槛落台阶（见 `engine.syncNpcDrift`），历史一根都不动。
 *
 * ⚠️ 它是**有界**的（值 = `permImpactOf(|净持仓| ÷ 流动性, σ)`，而净持仓被 `NPC.mom` 封顶），
 *    这是它**不能**写成 `s.flow` 一笔笔累加的原因 —— 见 `NPC` 的注释。
 */
function npcDriftAt(s, sym, j) {
  return stepValueAt(s.mkt && s.mkt[sym] && s.mkt[sym].npcDrift, j);
}

/**
 * 指数核的**静态衰减表**（NEXT-STEPS §8.7 · 方案 B′ · 2026-10-02）—— `DECAY[e] = 0.5^(e / shockHalf)`。
 *
 * ⚠️ **为什么要有它**：`npcShockAt` 要对**每一条**历史冲击求和，而 `factorFor` 被 `view.js` 逐根调用
 *    （可见窗口最多 240 根 × 每个已加载币）⇒ 12 年峰值下一帧的 `Math.pow` 次数可达 3×10⁶，
 *    实测 **30.0 ms / 帧**（合成 10537 条 × 60 根 × 5 币），是真正的帧预算杀手。
 *    换成一次表查之后实测 **1.8 ms / 帧**（约 16×），**逐位无损**（误差只来自 `Math.pow` 与建表同源）。
 * ⚠️ 表长取 **200 个半衰期**（`2⁻²⁰⁰ < 1e-60`）：再往后的贡献小于浮点噪声，一律按 0 计。
 *    4800 × 8B ≈ 38 KB，**全局一张**、不随币数增长、**不进存档**。
 */
const DECAY_MAX = 200 * NPC.shockHalf;
const DECAY = new Float64Array(DECAY_MAX);
for (let e = 0; e < DECAY_MAX; e++) DECAY[e] = Math.pow(0.5, e / NPC.shockHalf);

/**
 * 第 j 根上**NPC 级联成交**留下的瞬时冲击（v28 · 2026-10-02）。
 *
 * 形状与 `npcDrift` 一样是**只许追加的平行数组** `{ at: [], v: [] }`（`at` 恒等于写入那一刻的
 * `s.i` ⇒ 历史永不回头改写），但**取值方式不同**：不是「最后一个 `at ≤ j` 的台阶」，而是
 * **对每一笔按指数衰减求和** —— `Σ v_k × 0.5^((j − at_k) / NPC.shockHalf)`。
 *
 * ⚠️ 为什么不能写进 `s.flow`：那是**玩家**的永久痕迹通道（`perm ≥ 0.18` ＋ 慢幂律 `β = 0.3`），
 *    NPC 每小时都在注入 ⇒ `Σ t^-0.3` 无界累积，实测把显示价顶死在 `riseMax` 夹子上 97.67% 的时间。
 *    指数衰减的累积有上界（≈ 每小时注入量 × 34），级联因此「砸一波、数天内修复」。
 * @param {number} j 小时序号（可以是历史根）
 */
function npcShockAt(s, sym, j) {
  const tab = s.mkt && s.mkt[sym] && s.mkt[sym].npcShock;
  if (!tab || !tab.at.length) return 0;
  let sum = 0;
  for (let k = 0; k < tab.at.length; k++) {
    const e = j - tab.at[k];
    /* ⚠️ `break` 而不是 `continue`（方案 B′）：`at` **严格升序** —— 写入点 `pushNpcShock` 只往
       `at = 那一刻的 s.i` 追加、同小时还会合并；而 `rewindTo` 是**整条 `s.mkt` 归零重来**
       （`engine.js` 那句 `s.mkt = {}`）⇒ 永远不会出现「后来的 `at` 更小」。
       这一条顺带把**回顾页拖回 2013** 那种「j 远早于表尾」的读法从 O(n) 砍成 O(命中条数)。 */
    if (e < 0) break;                          // `at` 之后才生效（升序 ⇒ 之后全部无效）
    if (e < DECAY_MAX) sum += tab.v[k] * DECAY[e];
  }
  return sum;
}

/**
 * **玩家侧**的价格位移系数（不含 NPC 那层）—— 只有订单冲击＋持仓折价。
 * ⚠️ 热度的价格输入用它（见 `HEAT` 的口径注释）：玩家的成交要算进去（否则烧不起跟风），
 *    NPC 自己的连续偏移要剔除（否则会自激）。
 */
export function playerFactor(s, sym, j) {
  return shockFactorOf(residualAt(s, sym, j) + overhangAt(s, sym, j), !!s.god);
}

/**
 * 第 j 根的**价格位移系数** —— `market.candleAt` 唯一要乘的那个数。
 * 没有任何位移时恒等于 1（⇒ 与数据包逐位相同）。
 *
 * 三个来源相加：**订单冲击**（逐笔、幂律衰减）＋ **持仓抛压折价**（台阶表、不衰减）
 *             ＋ **NPC 散户净持仓偏移**（有界、台阶表）＋ **NPC 级联瞬时冲击**（有界、指数衰减）。
 *
 * ⚠️ 最后一项**只进这里、不进 `playerFactor`** —— 与 `npcDrift` 同一条纪律：
 *    热度的价格输入若含 NPC 自己的位移，就会自激（§73.5）。
 *
 * **两侧同时夹**（B1，2026-09-29；2026-10-02 收紧为 `SHOCK.fallMax` / `SHOCK.riseMax`）。
 * ⚠️ **夹子只属于普通局**（2026-10-07 用户拍板「上帝模式去掉封顶封底」）：`s.god` 非空时
 *    原样放行、不夹 —— 想拉多少拉多少（`1e-9` 下界仍保留：价格不能为 0）。
 *    挑战局 `s.god` 恒空 ⇒ 与普通局同一条夹子，行为与改动前逐位相同。
 */
export function factorFor(s, sym, j) {
  return shockFactorOf(residualAt(s, sym, j) + overhangAt(s, sym, j) + npcDriftAt(s, sym, j) + npcShockAt(s, sym, j), !!s.god);
}

/** 把一份「位移总量」夹进 `fallMax ~ riseMax` 并转成乘数（两个入口共用，保证同形）；
 *  `uncapped` = 上帝局不夹（见 `factorFor` 头注）。 */
function shockFactorOf(r, uncapped) {
  if (!r) return 1;
  const c = uncapped ? r : Math.min(SHOCK.riseMax, Math.max(SHOCK.fallMax, r));
  const f = 1 + c;
  return f > 1e-9 ? f : 1e-9;
}

