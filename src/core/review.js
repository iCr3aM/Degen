/** 全部回顾节点（已带 `at` / `sym` 字段，按时间排好）—— **只算这一次**
 *  ⚠️ `sym` 缺省是 `BTC`（见文件头）：每个节点都会把回顾切到它自己的币上。 */
export const RV_NODES = [
  ...allAnchors().map(a => ({ at: a.at, title: a.title, note: NOTE[a.t] || '', sym: ANCHOR_SYM[a.t] || 'BTC' })),
  ...EXTRA.map(e => ({ at: Math.round((e.t - GAME.start) / HOUR_MS), title: e.title, note: e.note, sym: e.sym || 'BTC' })),
].sort((a, b) => a.at - b.at);

/** 第 `i` 根小时 K 是不是某个节点（节点一律落在整点上，`===` 足够） */
export const nodeAt = i => RV_NODES.find(n => n.at === i) || null;

/**
 * 前方**最近的一个没被跳过**的节点（`at > i`）。
 * @param {Set<number>} [seen] 已跳过的节点时刻（`at`）—— 跳过的节点不再参与减速与停留
 */
export function nextNodeAt(i, seen) {
  for (const n of RV_NODES) if (n.at > i && !(seen && seen.has(n.at))) return n;
  return null;
}

/**
 * 减速曲线（方案 §3.5）—— 距下一个节点越近越慢，纯函数。
 *
 * | 距下一个节点 | 档位 |
 * |---|---|
 * | > 1 游戏日 | 巡航 `100x` |
 * | ≤ 1 游戏日 | `10x` |
 * | ≤ 6 游戏小时 | `1x` |
 *
 * ⚠️ 返回值是**天花板**：真正推进用的是 `min(玩家选的档, speedAt(i))` —— 玩家手动切到 `1x`
 *    就该一直 `1x`，而选 `100x` 的玩家在节点前会感到「自动慢下来」。
 * ⚠️ 已经跳过的节点不参与（`seen`）—— 否则刚说完「跳过」又在那里减速，很别扭。
 */
export function speedAt(i, seen) {
  const n = nextNodeAt(i, seen);
  if (!n) return RV_SPEEDS[RV_SPEEDS.length - 1];
  const d = n.at - i;
  return d > 24 ? 100 : d > 6 ? 10 : 1;
}