/** 组在 `time` 此刻可用：主体池非空（匿名族恒真）＋ 至少一个动作/对象已到期 */
function groupUsable(g, time) {
  if (g.ph && !entitiesOf(PH_KIND[g.ph], time).length) return false;
  if (!g.acts.some(a => time >= a.from)) return false;
  if (g.objs && !g.objs.length) return false;
  if (g.objs && !g.objs.some(o => time >= o.from)) return false;
  return true;
}
/** 从「已到期」的子集里抽一个词 */
const pickGated = (arr, seed, i, stream, salt, time) => {
  const ok = arr.filter(e => time >= e.from);
  return pickS(ok.length ? ok : arr, seed, i, stream, salt);
};

/**
 * 拼一句快讯的**正文片段**（不含 `【%S 快讯】` 前缀与数值尾）。
 * @returns {{tpl:string, dir:number}} `dir` = 本句方向（供立场账本）
 */
function assemble(seed, i, time, salt) {
  const avail = FAMS.filter(g => groupUsable(g, time));
  const g = pickS(avail.length ? avail : FAMS, seed, i, 11, salt);
  const head = g.ph ? g.ph : pickS(g.wh, seed, i, 15, salt);
  const act = pickGated(g.acts, seed, i, 12, salt, time);
  const obj = g.objs ? pickGated(g.objs, seed, i, 13, salt, time) : null;
  const tail = pickS(TAIL, seed, i, 14, salt);
  /* ⚠️ 占位符主体解析出来的多是**拉丁名**（Binance / 美国 SEC / 挪威主权基金…），
     `%X上线` 会连成「Binance上线」；中文匿名词（某场外大户）则不加空格。
     与假消息一侧 `%X 宣布…` 同一排版口径。 */
  const sep = g.ph ? ' ' : '';
  return { tpl: `${head}${sep}${act.w}${obj ? obj.w : ''}${tail}`, dir: act.t };
}

/** 快讯节奏（2026-10-11 二次收敛 · 用户拍板「参考**普通模式**的新闻频率」）——
 *
 *  基准怎么来的（实测，非估算）：跑满史实全程 105192 根，用引擎的 `pushLog` 去重口径
 *  （同一句连续重复只留一条）数**玩家实际看到**的新闻条数 ⇒ **74 条 / 12.01 年 ≈ 6.2 条/年**，
 *  换算 50x（`acc += dt × speed` ⇒ 1 真实秒 = 50 游戏小时）= **每 28.4 真实秒一条**。
 *  ⚠️ 上一版 `1/200`（每 200 游戏小时一条 ≈ 37 条/年）比普通模式**密约 6 倍** —— 用户报
 *     「仍需再次收敛」正是这条：架空世界没有史实锚点 / 巨鲸 / ETF，快讯就是它全部的新闻流，
 *     密度应当**对齐普通模式**，而不是自成一套更密的节奏。
 *  现口径 = 每 **60 游戏日**（1440h）一条 ⇒ 6.08 条/年、50x 下 ≈ **每 28.8 真实秒一条**
 *  （与普通模式的 28.4 秒一致）；1x 下 ≈ 24 分钟一条。 */
const CADENCE_HOURS = 1440;
const CADENCE = 1 / CADENCE_HOURS;

/**
 * 第 `i` 根小时的**架空快讯**（没有就是 `null`）。
 *
 * @param {number} seed 世界线种子（`s.ficSeed`）
 * @param {number} i 绝对小时序号
 * @param {number} [salt] 抽签盐（只影响「句子族 / 动作 / 实体」；**不影响节奏 / 币种 / 数值尾**）
 * @returns {{sym:string, tpl:string, dir:number}|null} `tpl` 是**未填充**的模板
 *   （`%S/%L/%A/%R/%H` ＋ 实体占位符 `%X/%Z…`），由引擎的
 *   `fillNewsEnts(...)` 在播报那一刻填进真值。
 */
export function ficNewsAt(seed, i, salt = 0) {
  const sd = (seed >>> 0) || 1;
  /* 节奏 / 币种 / 数值尾一律**不吃 salt** —— 避让重抽不会让频率或读数漂移。 */
  if (rnd(sd, 0x91, i, 0) >= CADENCE) return null;

  const t = GAME.start + i * HOUR_MS;
  /* 只从**此刻已上线**的币里抽（BTC 的 unlock 早于开局 ⇒ 恒在列） */
  let listed = COINS.filter(c => c.unlock <= t);
  if (!listed.length) listed = [COINS[0]];
  const sym = listed[Math.floor(rnd(sd, 0x91, i, 2) * listed.length) % listed.length].sym;

  const { tpl, dir } = assemble(sd, i, t, salt);
  let out = `【%S 快讯】${tpl}`;
  /* **数值展示**（2026-10-10 用户拍板「架空新闻可以有相关数值展示」）—— 约 70% 的快讯带一段
     事实性读数：现价 / 当日成交额 / 资金费率 / 市场热度。这些值由引擎在**播报那一刻**填真值
     （`fillNews` + `newsVars`），不是编的；**仍不含涨跌幅**（`%C/%c` 一律不用 —— 项目红线）。 */
  const roll = rnd(sd, 0x91, i, 3);
  if (roll < 0.28) out += '，现价 %L';
  else if (roll < 0.45) out += '，当日成交额 %A';
  else if (roll < 0.58) out += '，资金费率 %R';
  else if (roll < 0.70) out += '，市场热度 %H';
  return { sym, tpl: out, dir };
}

/* ═══════════════ 自检 / 验收辅助（仅测试用）═══════════════ */

/** 连续取 `n` 根的快讯（`null` 跳过）—— 供 sim-audit 统计丰富度与重复率 */
export function ficNewsSample(seed, i0, n) {
  const out = [];
  for (let k = 0; k < n; k++) { const v = ficNewsAt(seed, i0 + k); if (v) out.push(v); }
  return out;
}

